#!/bin/sh
# tor-fleet — one Tor process per SOCKS port, inside one container.
#
# The ECS task runs three proxy groups, and each group must leave through its
# OWN Tor instance (9050 / 9150 / 9250) so a ban on one circuit cannot take the
# other two with it. The single /etc/tor/torrc setup could only ever bind one
# port, and `restart-tor` killed every tor and relaunched exactly one — so a
# three-group config ended up with three groups sharing (or missing) a circuit.
#
# Control port convention is SOCKS port + 1, no cookie auth: the same rule
# scripts/restart-tor.sh and tor-fleet.js use, so NEWNYM / bootstrap probes work
# unchanged inside the container.
#
#   tor-fleet start     start one instance per port in TOR_PORTS
#   tor-fleet stop      kill every tor process in this container
#   tor-fleet restart   stop, then start (what restart-tor runs)
#   tor-fleet status    print which ports are listening
#
# TOR_PORTS defaults to "9050 9150 9250"; set it (space separated) to override.
set -u

TOR_PORTS="${TOR_PORTS:-9050 9150 9250}"
CONF_DIR="${TOR_CONF_DIR:-/etc/tor/instances}"
DATA_ROOT="${TOR_DATA_ROOT:-/var/lib/tor}"
TOR_USER="${TOR_USER:-debian-tor}"
TOR_BIN="${TOR_BIN:-tor}"

log() { printf '[tor-fleet] %s\n' "$*"; }

start_instance() {
  port="$1"
  conf="$CONF_DIR/torrc-$port"
  data="$DATA_ROOT/$port"
  mkdir -p "$CONF_DIR" "$data" || return 1
  if id "$TOR_USER" >/dev/null 2>&1; then
    chown "$TOR_USER:$TOR_USER" "$data" 2>/dev/null || true
  fi
  chmod 700 "$data"
  {
    echo "# Generated by tor-fleet — instance for SOCKS port $port"
    echo "SocksPort 127.0.0.1:$port"
    echo "SocksPolicy accept 127.0.0.1"
    echo "SocksPolicy reject *"
    echo "ControlPort 127.0.0.1:$((port + 1))"
    echo "CookieAuthentication 0"
    echo "DataDirectory $data"
    echo "ClientOnly 1"
    echo "MaxCircuitDirtiness 10"
    echo "NewCircuitPeriod 15"
    echo "User $TOR_USER"
    echo "Log notice stdout"
  } > "$conf" || return 1
  # Same orphan trick as the entrypoint: tor reparents to tini (PID 1) so the
  # killed instances are reaped instead of lingering as <defunct>, and its logs
  # keep landing in `docker logs`.
  nohup "$TOR_BIN" -f "$conf" >/proc/1/fd/1 2>/proc/1/fd/2 &
  log "started tor for SOCKS :$port (control :$((port + 1)), data $data)"
}

case "${1:-start}" in
  start)
    for port in $TOR_PORTS; do start_instance "$port"; done
    ;;
  stop)
    pkill -x "$TOR_BIN" 2>/dev/null || true
    pkill -x tor.real 2>/dev/null || true
    sleep 1
    log "stopped every tor instance"
    ;;
  restart)
    "$0" stop
    for port in $TOR_PORTS; do start_instance "$port"; done
    ;;
  status)
    # dash has no /dev/tcp, so the reachability probe is node's net.connect —
    # the same probe the entrypoint uses.
    for port in $TOR_PORTS; do
      if PORT="$port" node -e 'const n=require("net"),s=n.connect(process.env.PORT,"127.0.0.1",()=>{s.destroy();process.exit(0)});s.on("error",()=>process.exit(1));setTimeout(()=>process.exit(1),1500)' 2>/dev/null; then
        log ":$port listening"
      else
        log ":$port DOWN"
      fi
    done
    ;;
  *)
    echo "usage: tor-fleet {start|stop|restart|status}" >&2
    exit 2
    ;;
esac
